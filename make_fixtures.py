def _doc(title: str, body: str, head_extra: str = "") -> str:
    # The asset reference is the one every served page carries (9 to 298
    # times per capture); the classifier's served-page check reads it.
    return ('<!DOCTYPE html><html><head><title>%s</title>'
            '<link rel="stylesheet" href="https://s.gr-assets.com/assets/cut.css">'
            '%s</head><body>%s</body></html>' % (title, head_extra, body))


def _title(html: str) -> str:
    m = re.search(r"<title>(.*?)</title>", html, re.S)
    return m.group(1).strip() if m else ""


def _strip_forms(fragment: str) -> str:
    """Tiles carry shelf buttons: forms with a CSRF token and inline JS with
    another. The parser reads neither, so both go. Asset urls carry a
    32-hex build fingerprint (`loading-trans-<md5>.gif`), which is the shape
    of an API key and would teach the credential scan an exception, so the
    fingerprint goes too (§24: take it out rather than exempt it)."""
    fragment = re.sub(r"-[0-9a-f]{32}(\.[a-z]+)", r"\1", fragment)
    fragment = re.sub(r"<form\b.*?</form>", "", fragment, flags=re.S)
    fragment = re.sub(r"<script\b.*?</script>", "", fragment, flags=re.S)
    fragment = re.sub(r'<a [^>]*onclick="[^"]*authenticity_token[^"]*"[^>]*>',
                      '<a href="#">', fragment)
    return fragment


def _cut_microdata(html: str, keep: int) -> str:
    soup = P._soup(html)
    tiles = [_strip_forms(str(t)) for t in P._microdata_tiles(soup)[:keep]]
    box = P._pagination(html)
    pag = "<div>%s</div>" % re.sub(r"\s+", " ", str(box)) if box is not None else ""
    return _doc(_title(html), "<table>%s</table>%s" % ("".join(tiles), pag))


def _cut_shelf(html: str, keep: int) -> str:
    soup = P._soup(html)
    shown = re.search(r"Showing\s+[\d,]+\s*-\s*[\d,]+\s+of\s+[\d,]+", P._text(soup) or "")
    els = [_strip_forms(str(e)) for e in soup.select("div.elementList")[:keep]]
    return _doc(_title(html), "<div>%s</div>%s" % (shown.group(0) if shown else "", "".join(els)))


def _cut_series(html: str) -> str:
    parts = ['<div data-react-class="ReactComponents.SeriesList" data-react-props="%s"></div>' % p
             for p in P._SERIES_PROPS_RE.findall(html)]
    heads = P._SERIES_HEADER_RE.findall(html)
    sub = P._SERIES_WORKS_RE.search(html)
    body = "<div>%s</div>" % (sub.group(0) if sub else "")
    body += "".join("<h3>%s</h3>" % h for h in heads) + "".join(parts)
    return _doc(_title(html), body)


def _cut_rsc(html: str, keep: int) -> str:
    books = P._rsc_books(html)[:keep]
    flight = "".join(json.dumps(b, ensure_ascii=False, separators=(",", ":")) for b in books)
    push = "<script>self.__next_f.push([1,%s])</script>" % json.dumps(flight, ensure_ascii=False)
    page_of = P._PAGE_OF_RE.search(html)
    return _doc(_title(html), "<div>%s</div>%s" % (page_of.group(0) if page_of else "", push))


def _cut_book(html: str) -> str:
    """The book's own entities out of the Apollo cache, the key replaced."""
    nd = P.next_data(html)
    ap = P._apollo(nd)
    root = ap.get("ROOT_QUERY") or {}
    keep_root = {k: v for k, v in root.items()
                 if k == "__typename" or k.startswith(("getBookByLegacyId", "getSocialSignals"))}
    wanted = set()

    def refs(v):
        if isinstance(v, dict):
            if "__ref" in v and v["__ref"] not in wanted:
                wanted.add(v["__ref"])
                refs(ap.get(v["__ref"]))
            for x in v.values():
                refs(x)
        elif isinstance(v, list):
            for x in v:
                refs(x)

    refs(keep_root)
    ap2 = {"ROOT_QUERY": keep_root}
    for k in sorted(wanted):
        if k.startswith("User:"):
            # A Work's featured-notes creator is a person, not catalogue.
            continue
        ent = copy.deepcopy(ap[k])
        if k.startswith("Work:"):
            ent.pop("featuredKNH", None)
            ent.pop("giveaways", None)
        if k.startswith("Book:"):
            ent.pop("links", None)
        ap2[k] = ent
    pp = nd["props"]["pageProps"]
    nd2 = {"props": {"pageProps": {"apolloState": ap2, "params": pp.get("params"),
                                   "apiKey": PLACEHOLDER_KEY if pp.get("apiKey") else None}},
           "page": nd.get("page")}
    head = "".join('<script type="application/ld+json">%s</script>' % x
                   for x in P._JSONLD_RE.findall(html))
    body = '<script id="__NEXT_DATA__" type="application/json">%s</script>' % json.dumps(
        nd2, ensure_ascii=False)
    return _doc(_title(html), body, head)


_REVIEW_TEXTS = (
    "<b>Placeholder review.</b> The first paragraph of a review, standing in "
    "for a reader's words.<br /><br />A second paragraph after a break.",
    "A one-line placeholder review.",
    "<blockquote>A quoted opening line.</blockquote>Placeholder text after it.",
)


def _cut_reviews(text: str, keep: int) -> str:
    payload = json.loads(text)
    block = payload["data"]["getReviews"]
    block["edges"] = block["edges"][:keep]
    for i, e in enumerate(block["edges"], 1):
        n = e["node"]
        n["id"] = "kca://review:goodreads/amzn1.gr.review:goodreads.v1.PLACEHOLDER%03d" % i
        n["text"] = _REVIEW_TEXTS[(i - 1) % len(_REVIEW_TEXTS)]
        n["shelving"]["webUrl"] = GR + "/review/show/%d" % (900000000 + i)
        c = n.get("creator") or {}
        c["id"] = "kca://profile:goodreads/PLACEHOLDER%03d" % i
        c["legacyId"] = 100000000 + i
        c["name"] = "Reviewer %d" % i
        c["webUrl"] = GR + "/user/show/%d-reviewer-%d" % (100000000 + i, i)
    if (block.get("pageInfo") or {}).get("nextPageToken"):
        # Opaque and harmless, but a real cursor is a real position in a
        # real feed; any non-empty string exercises the same path.
        block["pageInfo"]["nextPageToken"] = "UExBQ0VIT0xERVI"
    return json.dumps(payload, ensure_ascii=False)


def _cut_waf(html: str) -> str:
    # The WAF's page is a few KB of its own markup, kept whole, with any
    # token-shaped value in it replaced.
    return re.sub(r'"(key|iv|context)"\s*:\s*"[^"]*"', r'"\1":"PLACEHOLDER"', html)


_EXT_TAG_RE = re.compile(r'<script[^>]*chrome-extension://[^>]*>\s*</script>|<captcha-widgets[^>]*>\s*</captcha-widgets>')


def _cut_cdp(html: str) -> str:
    """A book page cut as usual, with what the extension injected kept."""
    return _cut_book(html).replace("</head>", "".join(_EXT_TAG_RE.findall(html)) + "</head>", 1)


def _scrub_problems(fixture: str) -> list:
    problems = []
    if HEX32.search(fixture):
        problems.append("a 32-hex string")
    if APPSYNC_KEY.search(fixture):
        problems.append("an AppSync key")
    if CSRF.search(fixture):
        problems.append("a CSRF token")
    return problems


REPLACED = {"reviews": {"url", "sku", "text", "reviewer", "reviewer_id", "reviewer_url"}}


def _query(url: str, kind: str):
    if kind in ("reviews", "raw") and "appsync" in url:
        q, _ = P.query_from_url(GR + "/book/show/5907")
    else:
        q, _ = P.query_from_url(url)
    if kind == "reviews":
        q.mode = "reviews"
    return q


def _compare(orig, cut, kind, url, status) -> list:
    q = _query(url, kind)
    where = P.GRAPHQL_ENDPOINT if kind == "reviews" else url
    diffs = []
    s1, s2 = P.detect_page_state(orig, status, where), P.detect_page_state(cut, status, where)
    if s1 != s2:
        diffs.append("state %s != %s" % (s1, s2))
    if kind in ("raw", "waf"):
        return diffs
    if kind == "cdp":
        kind = "book"
    r1 = [asdict(r) for r in P.parse_page(orig, q, 1)]
    r2 = [asdict(r) for r in P.parse_page(cut, q, 1)]
    if len(r2) > len(r1):
        diffs.append("the cut holds more rows than the original")
    skip = {"scraped_at"} | REPLACED.get(kind, set())
    for a, b in zip(r1, r2):
        for k in a:
            if k not in skip and a[k] != b[k]:
                diffs.append("%s: %r != %r" % (k, a[k], b[k]))
    if kind in ("microdata", "rsc", "shelf", "series"):
        for fn in (P.served_page, P.pages_available, P.total_results):
            if fn(orig, q.kind) != fn(cut, q.kind):
                diffs.append("%s %r != %r" % (fn.__name__, fn(orig, q.kind), fn(cut, q.kind)))
    if kind == "book":
        a, b = P.book_landing(orig), P.book_landing(cut)
        a.pop("api_key")
        b.pop("api_key")
        if a != b:
            diffs.append("book_landing differs")
    return diffs


CUTTERS = {
    "microdata": lambda h, k: _cut_microdata(h, k), "shelf": lambda h, k: _cut_shelf(h, k),
    "series": lambda h, k: _cut_series(h), "rsc": lambda h, k: _cut_rsc(h, k),
    "book": lambda h, k: _cut_book(h), "reviews": lambda h, k: _cut_reviews(h, k),
    "notfound": lambda h, k: _doc(_title(h), "<h1>Page not found</h1>"),
    "none": lambda h, k: _doc(_title(h), "<div>No results.</div>"),
    "waf": lambda h, k: _cut_waf(h), "raw": lambda h, k: h,
    "cdp": lambda h, k: _cut_cdp(h),
}


def main(argv) -> int:
    cap = pathlib.Path(argv[1] if len(argv) > 1 else REPO / "captures")
    out, bad = {}, 0
    sources = dict(SOURCES)
    sources.update({k: v for k, v in OPTIONAL.items() if (cap / v[0]).exists()})
    for name, (fname, url, keep, kind, status) in sources.items():
        orig = (cap / fname).read_text(encoding="utf-8")
        cut = CUTTERS[kind](orig, keep)
        problems = _compare(orig, cut, kind, url, status) + _scrub_problems(cut)
        if problems:
            bad += 1
            print("FAIL %s: %s" % (name, "; ".join(problems)[:600]))
            continue
        out[name] = {"url": url, "status": status, "text": cut}
        print("ok   %-18s %7d -> %6d bytes" % (name, len(orig), len(cut)))
    if bad:
        print("%d fixture(s) refused; nothing written." % bad)
        return 1
    path = REPO / "fixtures_generated.json"
    path.write_text(json.dumps(out, ensure_ascii=False, indent=1, sort_keys=True) + "\n",
                    encoding="utf-8")
    print("wrote %s (%d fixtures)" % (path.name, len(out)))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
