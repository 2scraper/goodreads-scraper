#!/usr/bin/env python3
"""Cut the offline suite's fixtures out of real captures, and PROVE they parse
the same.

Its output is `fixtures_generated.json`, which `smoke_test.py` loads.

WHY A GENERATED FILE RATHER THAN INLINE LITERALS
------------------------------------------------
The family's rule is fixtures inline in `smoke_test.py`. Here a capture is a
whole page: a Listopia page is 780 KB and a book page 750 KB, most of it ads,
scripts and CSRF-bearing forms. Pasting even a trimmed one into a Python
source file would make the suite unreadable. The generated JSON sits beside
it, is regenerated by this script, and is checked by the suite for the same
properties inline fixtures would be (rakuten, polymarket and binance do the
same for the same reason).

WHAT YOU NEED TO RUN IT
-----------------------
Your own captures, in `captures/` (ignored by git), named as the SOURCES
table below expects. Take them with `--dump-html`, which writes exactly the
document the parser was given.

WHAT IT ENFORCES
----------------
  * every fixture is CUT from a real capture: the parts the parser reads,
    verbatim, inside a minimal document. Nothing is hand-written except the
    placeholders the scrub puts in;
  * each one parses IDENTICALLY to the untrimmed original for the records
    it keeps, every column, apart from the columns the scrub replaced, and
    states the same page state, served page, page count and total;
  * the scrub runs BEFORE anything is embedded:
      - the AppSync key the book page hands every visitor (`pageProps.apiKey`)
        and every CSRF `authenticity_token`. Neither grants anything to a
        reader of this repo, and neither belongs in it (§10);
      - a reviewer's name, profile id and url, and the review's own text and
        id. The checks need the STRUCTURE of a review, not a person's words
        (§10). Book, author and series data is the site's catalogue and is
        kept verbatim;
  * a fixture that still holds a 32-hex string, a `da2-` key or a CSRF token
    after the scrub is refused.

NOT VERBATIM: the search fixtures' React payload is RE-ENCODED. The page
streams ~250 KB of React Server Components data, and the fixture carries the
same Book objects the parser merged out of it, re-serialised as one push
chunk. The parser's path through it (decode the pushes, raw-decode each Book)
is the same; the byte layout is not.

    python3 make_fixtures.py [captures_dir]
"""
